package otel

import (
	"reflect"
	"strings"
	"testing"

	dbpreview "github.com/documentdb/documentdb-operator/api/preview"
)

func TestGenerateConfigMapDataWithOptions(t *testing.T) {
	spec := &dbpreview.MonitoringSpec{Enabled: true}

	def, err := GenerateConfigMapData("c", "ns", spec)
	if err != nil {
		t.Fatal(err)
	}
	empty, err := GenerateConfigMapDataWithOptions(Options{}, "c", "ns", spec)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(def, empty) {
		t.Fatal("empty options must produce the DocumentDB config")
	}

	custom, err := GenerateConfigMapDataWithOptions(Options{ClusterAttribute: "cosmos.cluster", Generator: "cosmos-operator"}, "c", "ns", spec)
	if err != nil {
		t.Fatal(err)
	}
	dyn := custom["dynamic.yaml"]
	if !strings.HasPrefix(dyn, "# Auto-generated by cosmos-operator.") || !strings.Contains(dyn, "cosmos.cluster") ||
		strings.Contains(dyn, "documentdb") {
		t.Fatalf("custom naming not applied:\n%s", dyn)
	}
}
